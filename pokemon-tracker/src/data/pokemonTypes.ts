// Normalize Pokemon name and return its types
export function getPokemonTypes(rawName: string): [PokemonType, PokemonType?] | null {
  if (!rawName) return null;

  // Normalize: trim, uppercase, remove extra spaces
  let name = rawName.trim().toUpperCase();

  // Check direct match first
  if (POKEMON_TYPES[name]) return POKEMON_TYPES[name] as [PokemonType, PokemonType?];

  // Check without shadow marker
  const baseName = name.replace(/\s*\(S\)\s*$/, '').trim();
  if (POKEMON_TYPES[baseName]) return POKEMON_TYPES[baseName] as [PokemonType, PokemonType?];

  // Try with (S) suffix stored explicitly
  const shadowName = baseName + ' (S)';
  if (POKEMON_TYPES[shadowName]) return POKEMON_TYPES[shadowName] as [PokemonType, PokemonType?];

  return null;
}

export function getTypeColor(type: PokemonType): string {
  const colors: Record<PokemonType, string> = {
    Normal: '#9FA19F', Fire: '#E62829', Water: '#2980EF', Electric: '#FAC000',
    Grass: '#3FA129', Ice: '#3DCEF3', Fighting: '#FF8000', Poison: '#9141CB',
    Ground: '#915121', Flying: '#81B9EF', Psychic: '#EF4179', Bug: '#91A119',
    Rock: '#AFA981', Ghost: '#704170', Dragon: '#5060E1', Dark: '#624D4E',
    Steel: '#60A1B8', Fairy: '#EF70EF',
  };
  return colors[type] || '#9FA19F';
}
